"""Generate the game's read-only catalogue from the canonical JSON registry."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    entries = json.loads((ROOT / 'data/mods/catalog.json').read_text(encoding='utf-8'))['entries']
    seen = set()
    rows = ['-- Generated by tools/generate_mod_catalog.py; edit data/mods/catalog.json.', 'return {']
    for entry in entries:
        if entry['id'] in seen:
            raise ValueError('Duplicate catalogue ID: ' + entry['id'])
        seen.add(entry['id'])
        fields = {key: entry[key] for key in ('id', 'name', 'category', 'author', 'version', 'description', 'source', 'page_url', 'download_url', 'compatibility', 'last_verified') if entry[key] is not None}
        fields['characters'] = ', '.join(entry['characters'])
        rows.append(' {' + ','.join(key + '=' + json.dumps(value, ensure_ascii=False) for key, value in fields.items()) + '},')
    return '\n'.join(rows + ['}', ''])


if __name__ == '__main__':
    (ROOT / 'engine/scripts/polish-fighters/mod_catalog.lua').write_text(render(), encoding='utf-8')
