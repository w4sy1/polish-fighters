"""Build isolated render-only compatibility metadata from exact sheet dimensions.
No pixel edits and no changes to frame IDs, hitboxes, physics or timing.
Packed strides are inferred only when the entire declared axis fits exactly.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image
from import_legacy import decode
from audit_pack_compatibility import SHEET


def build(root):
    root=Path(root);manifest=root/'package.manifest';source=manifest.read_text();assets={}
    for line in source.splitlines():
        if line.startswith('asset='):
            virtual,relative=line[6:].split('|');assets[virtual]=root/relative
    dimensions={}
    for name,p in assets.items():
        if p.suffix in ['.bmp','.png']:
            with Image.open(p) as image:dimensions[name]=list(image.size)
    layouts={}
    for p in assets.values():
        if p.suffix!='.dat':continue
        for _,name,w,h,cols,rows in SHEET.findall(decode(p.read_bytes())):
            if name not in dimensions:continue
            w,h,cols,rows=map(int,(w,h,cols,rows));actual=dimensions[name]
            sx=w if cols>1 and actual[0]==w*cols else w+1
            sy=h if rows>1 and actual[1]==h*rows else h+1
            key=f'{name}|{w}|{h}|{cols}|{rows}'
            if sx!=w+1 or sy!=h+1:
                layouts[key]={'resource':name,'cell':[w,h],'grid':[cols,rows],'stride':[sx,sy],
                              'dimensions':actual,'inferred_packed_axis':True,
                              'pixel_file_sha256':hashlib.sha256(assets[name].read_bytes()).hexdigest()}
    data={'scope':'Render-only packed-axis interpretation and intersection with physical image bounds; no inferred artwork',
          'dimensions':dimensions,'layouts':layouts}
    (root/'sprite-layouts.json').write_text(json.dumps(data,indent=2)+'\n')
    dims='\n'.join(' ['+json.dumps(k)+']={'+str(v[0])+','+str(v[1])+'},' for k,v in sorted(dimensions.items()))
    strides='\n'.join(' ['+json.dumps(k)+']={'+str(v['stride'][0])+','+str(v['stride'][1])+'},' for k,v in sorted(layouts.items()))
    lua='''-- Generated by tools/build_sprite_layouts.py; see sprite-layouts.json.
return function(base)
 local dimensions={
'''+dims+'''
 }
 local strides={
'''+strides+'''
 }
 local original=base.picture
 function base.picture(data,frame_id,offset)
  local resource,rect=original(data,frame_id,offset)
  if not resource then return nil end
  local frame=data.frames[frame_id]
  local picture=frame.picture+(offset or 0)
  for _,sheet in ipairs(data.sheets) do
   local cell=picture-sheet.first_picture
   if cell>=0 and cell<sheet.columns*sheet.rows then
    local key=resource.."|"..sheet.cell_width.."|"..sheet.cell_height.."|"..sheet.columns.."|"..sheet.rows
    local stride=strides[key]
    if stride then rect={cell%sheet.columns*stride[1],math.floor(cell/sheet.columns)*stride[2],sheet.cell_width,sheet.cell_height} end
    break
   end
  end
  local size=dimensions[resource]
  -- A source rectangle wholly beyond the bitmap has no drawable pixels.
  -- Preserve the original invisible result without sending invalid draw geometry.
  if size and (rect[1]>=size[1] or rect[2]>=size[2]) then return nil end
  -- Intersect partial sources with existing pixels, never stretch or invent cells.
  -- match_screen derives the flipped anchor from the returned visible width.
  if size then
   rect={rect[1],rect[2],math.min(rect[3],size[1]-rect[1]),math.min(rect[4],size[2]-rect[2])}
  end
  return resource,rect
 end
 return base
end
'''
    (root/'sprite_layout.lua').write_text(lua)
    entry='extend=base/game/object_data|sprite_layout.lua'
    if entry not in source:manifest.write_text(source+entry+'\n')
    return len(layouts)


if __name__=='__main__':
    for name in ['bleach','kate','reinforced']:print(name,build('content-packs/'+name),'packed declarations')
