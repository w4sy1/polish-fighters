local document={options={digipad=false},other='preserved'}
engine={read_settings=function() return document end,write_settings=function(value) document=value;return true end}
local options=require('base/game/options')
assert(options.current().touch_layout=='modern','migrate old joystick preference')
local values=options.current();values.touch_layout='classic'
assert(options.save(values) and options.load().touch_layout=='classic' and options.current().digipad)
values.touch_layout='modern';assert(options.save(values) and not options.current().digipad)
assert(document.other=='preserved')
local pad=require('base/ui/touch_gamepad')
local layout=options.default_gamepad()
local classic=pad.create(layout,true,'classic')
assert(classic.stick.fixed and #classic.buttons==3,'classic: arrows plus exactly three buttons')
local modern=pad.create(layout,false,'modern')
assert(not modern.stick.fixed)
local function frame(state,touches,mode,screen)
    return pad.update(state,{touch_active=true,touches=touches,screen=screen},mode or 'match')
end
local attack={id=2,x=modern.buttons[1].x,y=modern.buttons[1].y}
assert(not frame(modern,{attack}):find('c'),'modern attack waits for release')
assert(frame(modern,{}):find('c'),'tap fires on release')
assert(frame(modern,{}):find('c'),'two frames survive alternate input sampling')
assert(not frame(modern,{}):find('c'),'tap must not repeat automatically')
frame(modern,{attack})
frame(modern,{{id=2,x=attack.x-70,y=attack.y}})
local released=frame(modern,{})
assert(released:find('l') and not released:find('c'),'face the aimed direction first')
frame(modern,{})
local fired=frame(modern,{})
assert(fired:find('l') and fired:find('c'),'aim overrides conflicting movement then attacks')
frame(modern,{})
assert(frame(modern,{})=='')
frame(modern,{attack})
frame(modern,{},'pause')
assert(not frame(modern,{}):find('c'),'pause cancels gesture without firing')
frame(modern,{attack})
pad.update(modern,{touch_active=false})
assert(not frame(modern,{}):find('c'),'hiding cancels gesture without firing')
local held=frame(classic,{{id=1,x=160,y=280},{id=2,x=classic.buttons[1].x,y=classic.buttons[1].y}})
assert(held:find('u') and held:find('c'),'classic attack is held alongside arrows')
local joystick=pad.create(layout,false,'modern')
frame(joystick,{{id=1,x=125,y=440}})
local running=frame(joystick,{{id=1,x=190,y=440}})
assert(joystick.run_pulse,'large displacement starts the existing run pulse')
local start=pad.create(layout,false,'modern')
frame(start,{attack})
frame(start,{},nil,{left=0,top=0,right=1000,bottom=550})
assert(not start.attack_pulse and not start.aim_finger,'resize cancels old gesture coordinates')
local resumed=pad.create(layout,false,'modern')
frame(resumed,{attack})
frame(resumed,{attack},'pause')
frame(resumed,{attack})
assert(not frame(resumed,{}):find('c'),'held finger across pause must not start a fresh attack')
frame(resumed,{attack})
pad.update(resumed,{touch_active=false})
frame(resumed,{attack})
assert(not frame(resumed,{}):find('c'),'held finger across hidden overlay must not fire')
for _,style in ipairs({'classic','modern'}) do
 local menu=pad.create(layout,style=='classic',style)
 local button={id=12,x=menu.buttons[1].x,y=menu.buttons[1].y}
 assert(frame(menu,{button},'full'):find('c'),'menu attack must confirm immediately in '..style)
 assert(not menu.aim_finger and not menu.attack_pulse,'menu must not start an aiming gesture')
 assert(not frame(menu,{},'full'):find('c'),'menu release must not confirm again')
end
print('PASS: layout migration, classic multitouch, release aiming, sampling, run and cancellation')
